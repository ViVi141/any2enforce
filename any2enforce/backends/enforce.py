"""EnforceScript backend: IR -> EnforceScript (.c) source text.

All EnforceScript-specific syntax lives here. Every ⚠-marked mapping is
rendered conservatively and documented in docs/VERIFY.md; the Workbench
validation loop (validate/workbench.py) is the source of truth for them.
"""

from __future__ import annotations

from dataclasses import fields as dc_fields
from typing import Dict, List, Optional

from ..diagnostics import DiagnosticSink
from ..ir import (
    AUTO, BOOL, FLOAT, INT, STRING, VOID, AnnAssignStmt, ArrayType,
    AssignStmt, AttributeExpr, AugAssignStmt, BoolOpExpr, BinOpExpr,
    BreakStmt, CallExpr, ClassDef, CompClause, CompareExpr, ConstExpr,
    ContinueStmt, DictCompExpr, DictExpr, ErrorType, Expr, ExprStmt, ForStmt,
    FunctionDef, IfStmt, ImportStmt, JoinedStrExpr, ListCompExpr, ListExpr,
    MapType, MethodDef, Module, NameExpr, PassStmt, RangeForStmt, ReturnStmt,
    ScalarType, SetCompExpr, SetType, Span, Stmt, SubscriptExpr, TernaryExpr,
    Type, UnaryOpExpr, UnsupportedExpr, UnsupportedStmt, WhileStmt,
)

RESERVED = {
    "class", "modded", "sealed", "proto", "native", "external", "override",
    "ref", "auto", "typename", "vector", "bool", "float", "int", "string",
    "enum", "typedef", "static", "protected", "private", "public", "new",
    "delete", "null", "true", "false", "return", "if", "else", "while", "do",
    "for", "foreach", "switch", "case", "default", "break", "continue",
    "this", "super", "void", "const", "out", "in", "function", "not",
    "and", "or", "is", "init",
}


class EnforceBackend:
    def __init__(self, config: dict, diagnostics: DiagnosticSink) -> None:
        self.config = config
        self.diag = diagnostics
        self.naming = config.get("naming", {})
        self.policy = self.naming.get("policy", "keep")
        self.field_prefix = self.naming.get("field_prefix", "m_")
        self.prefix = self.naming.get("prefix", "")
        self.visibility = config.get("visibility", "protected")
        self.lines: List[str] = []
        self.indent = 0
        self._field_names: set = set()
        self._method_names: set = set()
        self._locals: Dict[str, Type] = {}
        self._scopes: List[set] = []  # EnforceScript uses block scoping (unlike Python)
        self._comp_tmp = 0

    # ==================================================================
    # entry
    # ==================================================================
    def emit(self, mod: Module) -> str:
        self.lines = []
        self.indent = 0
        self._line(f"// Generated by any2enforce v0.1 -- DO NOT EDIT")
        self._line(f"// Source: {mod.name}.py (Python -> EnforceScript)")
        self._line("")
        if mod.doc:
            self._emit_doc_comment(mod.doc)
        for imp in mod.imports:
            names = ", ".join(imp.names) if imp.names else ""
            self._line(f"// import {imp.module}" + (f" ({names})" if names else ""))
        if mod.imports:
            self._line("")
        for g in mod.globals:
            self._stmt(g)
            self._line("")
        for fn in mod.functions:
            self._emit_function(fn)
            self._line("")
        for cls in mod.classes:
            self._emit_class(cls)
            self._line("")
        # drop trailing blank lines
        while self.lines and self.lines[-1] == "":
            self.lines.pop()
        return "\n".join(self.lines) + "\n"

    # ==================================================================
    # declarations
    # ==================================================================
    def _emit_function(self, fn: FunctionDef) -> None:
        self._locals = getattr(fn, "locals", None) or {}
        ret = self._type(fn.return_type or VOID)
        if fn.doc:
            self._emit_doc_comment(fn.doc)
        self._line(f"{ret} {self._global_fn_id(fn.name)}({self._params(fn.params)})")
        self._emit_todos(fn.todos)
        self._emit_body(fn.body, predeclare={p.name for p in fn.params})

    def _emit_class(self, cls: ClassDef) -> None:
        self._field_names = {f.name for f in cls.fields}
        self._method_names = {m.name for m in cls.methods}
        if cls.doc:
            self._emit_doc_comment(cls.doc)
        head = f"class {self._type_id(cls.name)}"
        if cls.bases:
            head += " : " + ", ".join(self._type_id(b) for b in cls.bases)
        self._line(head)
        self._emit_todos(cls.todos)
        self._line("{")
        self.indent += 1
        if cls.fields:
            for f in cls.fields:
                default = self._field_default(f.type)
                note = ""
                if f.default is not None:
                    note = f"  // was initialized to {self._const(f.default)} in Python"
                # array/map/set fields are ref types in EnforceScript
                # (verified: `protected ref array<float> s_Means;` in ANNA)
                self._line(f"{self.visibility} {self._field_type(f.type)} "
                           f"{self._field_id(f.name)};{note}")
            self._line("")
        for i, m in enumerate(cls.methods):
            if i:
                self._line("")
            self._emit_method(cls, m)
        self.indent -= 1
        self._line("}")
        self._field_names = set()
        self._method_names = set()

    def _emit_method(self, cls: ClassDef, m: MethodDef) -> None:
        self._locals = getattr(m, "locals", None) or {}
        if m.is_constructor:
            name = self._type_id(cls.name)
            ret = "void"
        else:
            name = self._fn_id(m.name)
            ret = self._type(m.return_type or VOID)
        if m.doc:
            self._emit_doc_comment(m.doc)
        static = "static " if m.is_static and not m.is_constructor else ""
        self._line(f"{static}{ret} {name}({self._params(m.params)})")
        self._emit_todos(m.todos)
        self._emit_body(m.body, predeclare={p.name for p in m.params})

    def _params(self, params) -> str:
        out = []
        for p in params:
            decl = f"{self._type(p.type or AUTO)} {self._var_id(p.name)}"
            if p.default is not None:
                decl += f" = {self._const(p.default)}"
            out.append(decl)
        return ", ".join(out)

    # ==================================================================
    # statements
    # ==================================================================
    def _emit_body(self, body: List[Stmt], predeclare=()) -> None:
        self._line("{")
        self._scopes.append(set(predeclare))
        self.indent += 1
        if not body:
            self._line("// (empty body from Python 'pass' / docstring)")
        stmts = list(body)
        for i, stmt in enumerate(stmts):
            if isinstance(stmt, (IfStmt, WhileStmt, RangeForStmt, ForStmt)):
                self._hoist_block_vars(stmt, stmts[i + 1:])
            self._stmt(stmt)
        self.indent -= 1
        self._line("}")
        self._scopes.pop()

    # ------------------------------------------------------------------
    # scope helpers (EnforceScript = block scoping; Python = function scoping)
    # ------------------------------------------------------------------
    def _in_scope(self, name: str) -> bool:
        return any(name in s for s in self._scopes)

    def _declare(self, name: str) -> None:
        if self._scopes:
            self._scopes[-1].add(name)
        else:
            self._scopes.append({name})

    def _hoist_block_vars(self, stmt: Stmt, remaining: List[Stmt]) -> None:
        """Names first-assigned inside a nested block (if/while/for body) but
        used AFTER the block are function-scoped in Python but block-scoped in
        EnforceScript — declare them at the current level first (typed, from
        sema), then the block assignments become plain assignments."""
        assigned = set()
        self._assigned_in(stmt, assigned)
        if not assigned:
            return
        used: set = set()
        for s in remaining:
            self._collect_names(s, used)
        for name in sorted(assigned & used):
            if self._in_scope(name):
                continue
            t = self._locals.get(name)
            if t is None:
                self.diag.warning(
                    "hoist-type",
                    f"cannot determine type for hoisted variable '{name}'",
                    getattr(stmt, "span", None),
                )
                self._line(f"auto {self._var_id(name)} = 0;")
            else:
                self._line(f"{self._type(t)} {self._var_id(name)}"
                           f" = {self._default_init(t)};")
            self._declare(name)

    def _assigned_in(self, node, out: set) -> None:
        if isinstance(node, (AssignStmt, AugAssignStmt)) \
                and isinstance(node.target, NameExpr):
            out.add(node.target.name)
        elif isinstance(node, AnnAssignStmt) and isinstance(node.target, NameExpr):
            out.add(node.target.name)
        elif isinstance(node, IfStmt):
            for _, body in node.branches:
                for s in body:
                    self._assigned_in(s, out)
            for s in node.orelse:
                self._assigned_in(s, out)
        elif isinstance(node, (WhileStmt, RangeForStmt, ForStmt)):
            for s in node.body:
                self._assigned_in(s, out)

    def _collect_names(self, node, out: set) -> None:
        """Collect every NameExpr in the IR subtree (used for lookahead)."""
        if isinstance(node, NameExpr):
            out.add(node.name)
            return
        for f in dc_fields(node):
            v = getattr(node, f.name)
            if isinstance(v, (Expr, Stmt)):
                self._collect_names(v, out)
            elif isinstance(v, list):
                for item in v:
                    if isinstance(item, (Expr, Stmt)):
                        self._collect_names(item, out)
                    elif isinstance(item, tuple):
                        for sub in item:
                            if isinstance(sub, (Expr, Stmt)):
                                self._collect_names(sub, out)
                            elif isinstance(sub, list):
                                for s2 in sub:
                                    if isinstance(s2, (Expr, Stmt)):
                                        self._collect_names(s2, out)

    def _default_init(self, t: Type) -> str:
        if isinstance(t, ScalarType):
            return {"int": "0", "float": "0.0", "bool": "false",
                    "string": '""'}.get(t.name, "0")
        if isinstance(t, ArrayType):
            return "{ }"
        if isinstance(t, MapType):
            return f"new {t.render()}()"
        return "null"

    def _stmt(self, stmt: Stmt) -> None:
        if isinstance(stmt, AssignStmt):
            self._assign(stmt)
        elif isinstance(stmt, AnnAssignStmt):
            if isinstance(stmt.value, (ListCompExpr, DictCompExpr, SetCompExpr)):
                self._comp_assign(stmt.target, stmt.value, declared_type=stmt.type)
            elif isinstance(stmt.target, NameExpr):
                t = stmt.type or AUTO
                self._declare(stmt.target.name)
                if isinstance(stmt.value, ListExpr):
                    # xs: list[T] = [...] -> `array<T> xs = { ... };`
                    items = ", ".join(self._expr(i) for i in stmt.value.items)
                    self._line(f"{self._type(t)} {self._var_id(stmt.target.name)}"
                               f" = {{ {items} }};")
                else:
                    self._line(f"{self._type(t)} {self._var_id(stmt.target.name)}"
                               f"{' = ' + self._expr(stmt.value) if stmt.value else ''};")
            else:
                self._line(f"{self._expr(stmt.target)} = {self._expr(stmt.value)};"
                           if stmt.value else f"{self._expr(stmt.target)} = 0;")
        elif isinstance(stmt, AugAssignStmt):
            self._aug_assign(stmt)
        elif isinstance(stmt, ExprStmt):
            if isinstance(stmt.expr, UnsupportedExpr):
                self._line(f"// [any2enforce:error] {stmt.expr.reason}")
            else:
                self._line(f"{self._expr(stmt.expr)};")
        elif isinstance(stmt, ReturnStmt):
            if stmt.value is None:
                self._line("return;")
            elif isinstance(stmt.value, TernaryExpr):
                self._ternary_return(stmt.value)
            elif isinstance(stmt.value, (ListCompExpr, DictCompExpr, SetCompExpr)):
                self._comp_return(stmt.value)
            else:
                self._line(f"return {self._expr(stmt.value)};")
        elif isinstance(stmt, IfStmt):
            self._if(stmt)
        elif isinstance(stmt, WhileStmt):
            self._line(f"while ({self._expr(stmt.cond)})")
            self._emit_body(stmt.body)
        elif isinstance(stmt, RangeForStmt):
            self._range_for(stmt)
        elif isinstance(stmt, ForStmt):
            self._foreach(stmt)
        elif isinstance(stmt, BreakStmt):
            self._line("break;")
        elif isinstance(stmt, ContinueStmt):
            self._line("continue;")
        elif isinstance(stmt, PassStmt):
            self._line("// pass")
        elif isinstance(stmt, ImportStmt):
            self._line(f"// import {stmt.module}")
        elif isinstance(stmt, UnsupportedStmt):
            self._line(f"// [any2enforce:{stmt.level}] unsupported: {stmt.reason}")
            if stmt.source_text:
                for src in stmt.source_text.splitlines():
                    self._line(f"//   {src}")
        else:
            self._line(f"// [any2enforce:error] unhandled statement {type(stmt).__name__}")

    def _assign(self, stmt: AssignStmt) -> None:
        if isinstance(stmt.value, DictExpr):
            # dict literal -> map literal lowering (name or field target)
            self._map_literal(stmt.target, stmt.value)
            return
        if isinstance(stmt.value, ListExpr):
            self._list_assign(stmt)
            return
        if isinstance(stmt.value, TernaryExpr):
            self._ternary_assign(stmt)
            return
        if isinstance(stmt.value, (ListCompExpr, DictCompExpr, SetCompExpr)):
            self._comp_assign(stmt.target, stmt.value)
            return
        target = self._expr(stmt.target)
        value = self._expr(stmt.value)
        if isinstance(stmt.target, NameExpr):
            if self._in_scope(stmt.target.name):
                self._line(f"{target} = {value};")
            else:
                self._declare(stmt.target.name)
                self._line(f"auto {target} = {value};")
        else:
            self._line(f"{target} = {value};")

    def _list_assign(self, stmt: AssignStmt) -> None:
        """array literal -> `array<T> x = { ... };` (verified syntax:
        `array<Class> attributes = {};`, `testSuites = {testSuite};`)"""
        items = ", ".join(self._expr(i) for i in stmt.value.items)
        lit = f"{{ {items} }}"
        if isinstance(stmt.target, NameExpr):
            name = self._var_id(stmt.target.name)
            t = stmt.value.type if isinstance(stmt.value.type, ArrayType) else None
            if t is None:
                self.diag.error(
                    "list-type",
                    "cannot infer list element type; annotate the variable, "
                    "e.g. `xs: list[int] = [...]`",
                    stmt.value.span,
                )
                t = ArrayType(FLOAT)
            if self._in_scope(stmt.target.name):
                self._line(f"{name} = {lit};")
            else:
                self._declare(stmt.target.name)
                self._line(f"{self._type(t)} {name} = {lit};")
        else:
            self._line(f"{self._expr(stmt.target)} = {lit};")

    def _map_literal(self, target: Expr, d: DictExpr) -> None:
        """dict literal -> `map<K,V> name = new map<K,V>(); name[k] = v; ...`
        (map subscript `[]` read/write verified against Reforger scripts).
        Target may be a local name or a field (`self.x = {...}`)."""
        kt, vt = self._dict_types(d)
        if kt is None or vt is None:
            self.diag.error(
                "dict-type",
                "cannot infer dict key/value types (annotate the variable, "
                "e.g. `config: dict[str, int] = ...`)",
                d.span,
            )
            kt, vt = kt or FLOAT, vt or FLOAT
        if isinstance(target, NameExpr):
            name = self._var_id(target.name)
            if self._in_scope(target.name):
                self._line(f"{name} = new map<{kt.render()}, {vt.render()}>();")
            else:
                self._declare(target.name)
                self._line(f"map<{kt.render()}, {vt.render()}> {name} = "
                           f"new map<{kt.render()}, {vt.render()}>();")
        else:
            name = self._expr(target)
            self._line(f"{name} = new map<{kt.render()}, {vt.render()}>();")
        for k, v in d.items:
            self._line(f"{name}[{self._expr(k)}] = {self._expr(v)};")

    def _ternary_assign(self, stmt: AssignStmt) -> None:
        """`x = a if c else b` -> `T x = b; if (c) { x = a; }`
        (EnforceScript has NO ternary operator - verified)"""
        t = stmt.value
        if isinstance(stmt.target, NameExpr) and not self._in_scope(stmt.target.name):
            self._declare(stmt.target.name)
            self._line(f"auto {self._var_id(stmt.target.name)} = {self._expr(t.if_false)};")
        else:
            self._line(f"{self._expr(stmt.target)} = {self._expr(t.if_false)};")
        self._line(f"if ({self._expr(t.cond)})")
        self._emit_body([AssignStmt(stmt.target, t.if_true, span=stmt.span)])

    def _ternary_return(self, t: TernaryExpr) -> None:
        self._line(f"if ({self._expr(t.cond)})")
        self._line("{")
        self.indent += 1
        self._line(f"return {self._expr(t.if_true)};")
        self.indent -= 1
        self._line("}")
        self._line("else")
        self._line("{")
        self.indent += 1
        self._line(f"return {self._expr(t.if_false)};")
        self.indent -= 1
        self._line("}")

    def _comp_assign(self, target: Expr, comp: Expr,
                     declared_type: Optional[Type] = None) -> None:
        """Lower list/dict/set comprehension at assignment (like ternary)."""
        ctype = declared_type if isinstance(
            declared_type, (ArrayType, MapType, SetType)
        ) else None
        if ctype is None:
            ctype = getattr(comp, "type", None)
        if not isinstance(ctype, (ArrayType, MapType, SetType)):
            self.diag.error(
                "comp-type",
                "cannot determine comprehension container type; annotate the "
                "target (e.g. `ys: list[int] = [...]`)",
                comp.span,
            )
            if isinstance(comp, DictCompExpr):
                ctype = MapType(FLOAT, FLOAT)
            elif isinstance(comp, SetCompExpr):
                ctype = SetType(FLOAT)
            else:
                ctype = ArrayType(FLOAT)
        dest = self._declare_empty_container(target, ctype)
        self._emit_comp_clauses(comp, dest, 0)

    def _comp_return(self, comp: Expr) -> None:
        ctype = getattr(comp, "type", None)
        if not isinstance(ctype, (ArrayType, MapType, SetType)):
            self.diag.error(
                "comp-type",
                "cannot determine comprehension return type; annotate the "
                "function return type",
                comp.span,
            )
            if isinstance(comp, DictCompExpr):
                ctype = MapType(FLOAT, FLOAT)
            elif isinstance(comp, SetCompExpr):
                ctype = SetType(FLOAT)
            else:
                ctype = ArrayType(FLOAT)
        tmp = f"_pyComp{self._comp_tmp}"
        self._comp_tmp += 1
        dest = self._declare_empty_container(NameExpr(tmp, span=comp.span), ctype)
        self._emit_comp_clauses(comp, dest, 0)
        self._line(f"return {dest};")

    def _declare_empty_container(self, target: Expr, ctype: Type) -> str:
        """Emit empty array/map/set declaration; return destination name text."""
        if isinstance(ctype, ArrayType):
            empty = "{}"
            typ_s = self._type(ctype)
        elif isinstance(ctype, MapType):
            empty = f"new {self._type(ctype)}()"
            typ_s = self._type(ctype)
        elif isinstance(ctype, SetType):
            empty = f"new {self._type(ctype)}()"
            typ_s = self._type(ctype)
        else:
            empty = "{}"
            typ_s = "auto"
        if isinstance(target, NameExpr):
            name = self._var_id(target.name)
            if self._in_scope(target.name):
                self._line(f"{name} = {empty};")
            else:
                self._declare(target.name)
                self._line(f"{typ_s} {name} = {empty};")
            return name
        name = self._expr(target)
        self._line(f"{name} = {empty};")
        return name

    def _emit_comp_clauses(self, comp: Expr, dest: str, idx: int) -> None:
        clauses = comp.clauses
        if idx >= len(clauses):
            self._emit_comp_insert(comp, dest)
            return
        clause = clauses[idx]
        if clause.is_range:
            self._emit_comp_range_header(clause)
        else:
            self._emit_comp_foreach_header(clause)
        self._line("{")
        self.indent += 1
        self._scopes.append({clause.target.name})
        self._emit_comp_ifs(clause.ifs, comp, dest, idx)
        self._scopes.pop()
        self.indent -= 1
        self._line("}")

    def _emit_comp_ifs(self, ifs: List[Expr], comp: Expr, dest: str,
                      clause_idx: int) -> None:
        if not ifs:
            self._emit_comp_clauses(comp, dest, clause_idx + 1)
            return
        self._line(f"if ({self._expr(ifs[0])})")
        self._line("{")
        self.indent += 1
        self._emit_comp_ifs(ifs[1:], comp, dest, clause_idx)
        self.indent -= 1
        self._line("}")

    def _emit_comp_insert(self, comp: Expr, dest: str) -> None:
        if isinstance(comp, ListCompExpr) or isinstance(comp, SetCompExpr):
            self._line(f"{dest}.Insert({self._expr(comp.elt)});")
        elif isinstance(comp, DictCompExpr):
            self._line(
                f"{dest}[{self._expr(comp.key)}] = {self._expr(comp.value)};")
        else:
            self._line(f"// [any2enforce:error] unhandled comprehension")

    def _emit_comp_foreach_header(self, clause: CompClause) -> None:
        t = clause.elem_type
        if isinstance(t, ErrorType) or t is None:
            render = "auto"
            if t is None:
                self.diag.error(
                    "comp-foreach-type",
                    "missing comprehension foreach element type",
                    clause.span,
                )
        else:
            render = self._type(t)
        it = clause.iterable
        self._line(
            f"foreach ({render} {self._var_id(clause.target.name)} : "
            f"{self._expr(it) if it is not None else '/*missing*/'})"
        )

    def _emit_comp_range_header(self, clause: CompClause) -> None:
        var = self._var_id(clause.target.name)
        lo, hi = clause.lo, clause.hi
        if lo is None or hi is None:
            self.diag.error(
                "comp-range", "incomplete range() in comprehension", clause.span)
            lo = lo or ConstExpr(0)
            hi = hi or ConstExpr(0)
        temps: List[str] = []
        for label, e in (("lo", lo), ("hi", hi)):
            if not _is_simple(e):
                tmp = f"_pyRange{len(temps)}"
                self._line(f"int {tmp} = {self._expr(e)};")
                temps.append(tmp)
                if label == "lo":
                    lo = NameExpr(tmp)
                else:
                    hi = NameExpr(tmp)
        step = clause.step
        if step is None or (isinstance(step, ConstExpr) and step.value == 1):
            cond = f"{var} < {self._expr(hi)}"
            inc = f"{var}++"
        elif isinstance(step, ConstExpr) and isinstance(step.value, int) and step.value > 1:
            cond = f"{var} < {self._expr(hi)}"
            inc = f"{var} += {step.value}"
        elif isinstance(step, ConstExpr) and isinstance(step.value, int) and step.value < 0:
            cond = f"{var} > {self._expr(hi)}"
            inc = f"{var} -= {-step.value}"
        else:
            self.diag.error(
                "range-step",
                "range() with non-constant step is not supported in v0.1",
                step.span if step else clause.span,
            )
            cond = f"{var} < {self._expr(hi)}"
            inc = f"{var}++"
        self._line(f"for (int {var} = {self._expr(lo)}; {cond}; {inc})")

    def _aug_assign(self, stmt: AugAssignStmt) -> None:
        t = self._expr(stmt.target)
        v = self._expr(stmt.value)
        if stmt.op == "//":
            self._line(f"{t} = Math.Floor({t} / {v});")
        elif stmt.op == "**":
            self._line(f"{t} = Math.Pow({t}, {v});")
        elif stmt.op in ("+", "-", "*", "/", "%"):
            self._line(f"{t} {stmt.op}= {v};")
        else:
            self._line(f"// [any2enforce:error] unsupported augmented operator '{stmt.op}'")

    def _if(self, stmt: IfStmt) -> None:
        for i, (cond, body) in enumerate(stmt.branches):
            kw = "if" if i == 0 else "else if"
            self._line(f"{kw} ({self._expr(cond)})")
            self._emit_body(body)
        if stmt.orelse:
            self._line("else")
            self._emit_body(stmt.orelse)

    def _range_for(self, stmt: RangeForStmt) -> None:
        var = self._var_id(stmt.target.name)
        lo, hi = stmt.lo, stmt.hi
        temps: List[str] = []
        for label, e in (("lo", lo), ("hi", hi)):
            if not _is_simple(e):
                tmp = f"_pyRange{len(temps)}"
                self._line(f"int {tmp} = {self._expr(e)};")
                temps.append(tmp)
                if label == "lo":
                    lo = NameExpr(tmp)
                else:
                    hi = NameExpr(tmp)
        step = stmt.step
        if step is None or (isinstance(step, ConstExpr) and step.value == 1):
            cond = f"{var} < {self._expr(hi)}"
            inc = f"{var}++"
        elif isinstance(step, ConstExpr) and isinstance(step.value, int) and step.value > 1:
            cond = f"{var} < {self._expr(hi)}"
            inc = f"{var} += {step.value}"
        elif isinstance(step, ConstExpr) and isinstance(step.value, int) and step.value < 0:
            cond = f"{var} > {self._expr(hi)}"
            inc = f"{var} -= {-step.value}"
        else:
            self.diag.error(
                "range-step",
                "range() with non-constant step is not supported in v0.1",
                step.span if step else stmt.span,
            )
            cond = f"{var} < {self._expr(hi)}"
            inc = f"{var}++"
        self._line(f"for (int {var} = {self._expr(lo)}; {cond}; {inc})")
        # loop var is block-scoped in EnforceScript: visible in the body only
        self._emit_body(stmt.body, predeclare={stmt.target.name})

    def _foreach(self, stmt: ForStmt) -> None:
        t = stmt.elem_type
        if isinstance(t, ErrorType):
            render = "auto"
        elif t is None:
            render = "auto"
            self.diag.error(
                "foreach-type", "missing foreach element type", stmt.span)
        else:
            render = self._type(t)
        self._line(f"foreach ({render} {self._var_id(stmt.target.name)} : "
                   f"{self._expr(stmt.iterable)})")
        self._emit_body(stmt.body, predeclare={stmt.target.name})

    # ==================================================================
    # expressions
    # ==================================================================
    def _expr(self, e: Expr) -> str:
        if isinstance(e, NameExpr):
            return self._var_id(e.name)
        if isinstance(e, ConstExpr):
            return self._const(e)
        if isinstance(e, BinOpExpr):
            return self._binop(e)
        if isinstance(e, BoolOpExpr):
            joiner = " && " if e.op == "and" else " || "
            return joiner.join(self._p(v) for v in e.values)
        if isinstance(e, CompareExpr):
            parts = []
            left = e.left
            for op, right in zip(e.ops, e.comparators):
                r = self._p(right)
                if op == "is":
                    if isinstance(right, ConstExpr) and right.value is None:
                        parts.append(f"{self._p(left)} == null")
                    else:
                        self.diag.warning(
                            "is-identity",
                            "'is' identity comparison mapped to '=='",
                            e.span,
                        )
                        parts.append(f"{self._p(left)} == {r}")
                elif op == "is not":
                    if isinstance(right, ConstExpr) and right.value is None:
                        parts.append(f"{self._p(left)} != null")
                    else:
                        self.diag.warning(
                            "is-identity",
                            "'is not' identity comparison mapped to '!='",
                            e.span,
                        )
                        parts.append(f"{self._p(left)} != {r}")
                elif op in ("in", "not in"):
                    # verified: array.Contains (V06), map.Contains (P09),
                    # string.Contains (string.c API) — all compile & run
                    container = right
                    t = self._expr_type(container)
                    if t is None:
                        self.diag.warning(
                            "in-type",
                            "membership test on unknown type; emitted as "
                            ".Contains() (verify it exists on the type)",
                            e.span,
                        )
                    contained = f"{self._p(container)}.Contains({self._p(left)})"
                    parts.append(f"!{contained}" if op == "not in" else contained)
                else:
                    parts.append(f"{self._p(left)} {op} {r}")
                left = right
            return " && ".join(parts)
        if isinstance(e, UnaryOpExpr):
            if e.op == "not":
                return f"!{self._p(e.operand)}"
            return f"-{self._p(e.operand)}"
        if isinstance(e, CallExpr):
            return self._call(e)
        if isinstance(e, AttributeExpr):
            return self._attr_access(e)
        if isinstance(e, SubscriptExpr):
            base = self._expr(e.value)
            idx = self._expr(e.index)
            # map/array/string all support [] in EnforceScript (verified)
            return f"{base}[{idx}]"
        if isinstance(e, ListExpr):
            self.diag.error(
                "list-expr",
                "array literal `[...]` is only supported in assignment in v0.1 "
                "(EnforceScript `{ ... }` is a declaration initializer, not a "
                "general expression)",
                e.span,
            )
            return "/* [any2enforce:error] array literal in expression */ 0"
        if isinstance(e, DictExpr):
            self.diag.error(
                "dict-expr",
                "dict literal is only supported as a direct assignment value in v0.1",
                e.span,
            )
            return "new map<float, float>()"
        if isinstance(e, JoinedStrExpr):
            return self._fstring(e)
        if isinstance(e, TernaryExpr):
            self.diag.error(
                "ternary-expr",
                "ternary `a if c else b` in expression context is not supported "
                "in v0.1 (EnforceScript has no ternary); use it as a standalone "
                "assignment or return",
                e.span,
            )
            return "0"
        if isinstance(e, (ListCompExpr, DictCompExpr, SetCompExpr)):
            kind = "list" if isinstance(e, ListCompExpr) else (
                "dict" if isinstance(e, DictCompExpr) else "set")
            self.diag.error(
                "comp-expr",
                f"{kind} comprehension escaped lift pass; this is an internal "
                "error — please report",
                e.span,
            )
            return "/* [any2enforce:error] comprehension */ 0"
        if isinstance(e, UnsupportedExpr):
            return f"/* [any2enforce:error] {e.reason} */ 0"
        return "/* [any2enforce:error] unhandled expression */ 0"

    def _binop(self, e: BinOpExpr) -> str:
        l, r = self._p(e.left), self._p(e.right)
        if e.op == "//":
            return f"Math.Floor({l} / {r})"
        if e.op == "**":
            return f"Math.Pow({l}, {r})"
        if e.op == "%":
            lt = self._expr_type(e.left)
            if lt is STRING:
                return self._py_string_format(e.left, e.right)
            # EnforceScript has no reliable '%' operator: the user's compiler
            # rejects `int % int` ('Unknown operator %') despite one corpus
            # sample; the shipped int-modulo idiom is Math.Mod (verified:
            # `switch (Math.Mod(i, 3))`). Always emit Math.Mod.
            return f"Math.Mod({l}, {r})"
        return f"{l} {e.op} {r}"

    def _py_string_format(self, fmt_expr: Expr, val_expr: Expr) -> str:
        """Python old-style `"..." % x` -> string.Format() (verified API)."""
        if isinstance(fmt_expr, ConstExpr) and isinstance(fmt_expr.value, str):
            fmt, n = _convert_py_format(fmt_expr.value)
            if n == 0:
                return f'"{_escape(fmt)}"'
            if n > 1:
                self.diag.warning(
                    "py-format-multi",
                    "multi-value % formatting needs a tuple; only the first "
                    "placeholder is filled in v0.1",
                    fmt_expr.span,
                )
            return f'string.Format("{_escape(fmt)}", {self._expr(val_expr)})'
        self.diag.warning(
            "py-format",
            "non-literal format string in % formatting; emitted as string.Format()",
            fmt_expr.span,
        )
        return f'string.Format({self._expr(fmt_expr)}, {self._expr(val_expr)})'

    def _call(self, e: CallExpr) -> str:
        if e.kwargs:
            self.diag.error(
                "call-kwargs",
                "keyword arguments in calls are not supported in v0.1",
                e.span,
                note="pass arguments positionally",
            )
        args: List[str] = []
        for a in e.args:
            if isinstance(a, ListExpr):
                # verified: inline array literal as call argument (V05:
                # `Sum({1, 2, 3})` compiles and returns 6)
                items = ", ".join(self._expr(i) for i in a.items)
                args.append(f"{{ {items} }}")
            else:
                args.append(self._expr(a))
        if isinstance(e.func, NameExpr):
            name = e.func.name
            if name == "print":
                return self._print_call(e, args)
            if name == "len":
                return self._len_call(e, args)
            if name == "str":
                return self._str_call(e, args)
            if name == "int":
                return f"(int)({args[0]})" if args else "(int)(0)"
            if name == "float":
                return f"(float)({args[0]})" if args else "(float)(0)"
            if name == "bool":
                self.diag.warning(
                    "bool-cast",
                    "'bool(x)' mapped to 'x != 0' (approximation)",
                    e.span,
                )
                return f"({args[0]} != 0)" if args else "false"
            if name == "range":
                self.diag.error(
                    "range-expr",
                    "range() outside a for-loop is not supported in v0.1",
                    e.span,
                )
                return "0"
            if name == "abs":
                return self._abs_call(e, args)
            if name in ("min", "max"):
                return self._minmax_call(e, name, args)
            if name == "sum":
                self.diag.error(
                    "builtin-sum",
                    "sum() is not supported in v0.1 (expand the loop manually)",
                    e.span,
                )
                return "0"
            if name == "super":
                self.diag.error(
                    "unsupported-super",
                    "bare super() is not supported; only super().method(...) "
                    "and super().__init__(...) are handled",
                    e.span,
                )
                return "0"
            return f"{self._global_fn_id(name)}({', '.join(args)})"
        if isinstance(e.func, AttributeExpr):
            if _is_super_expr(e.func.value):
                # super().method(...) -> super.Method(...) (verified: 1357 files)
                return f"super.{self._method_id(e.func.attr)}({', '.join(args)})"
            if isinstance(e.func.value, NameExpr) and e.func.value.name == "this":
                # self.method(...) -> bare method call (verified convention)
                return f"{self._method_id(e.func.attr)}({', '.join(args)})"
            if e.func.attr == "append":
                # list.append(x) -> arr.Insert(x) (verified: ANNA MLP uses
                # Insert; array has no append)
                obj = self._expr(e.func.value)
                return f"{obj}.Insert({', '.join(args)})"
            obj = self._expr(e.func.value)
            meth = self._method_id(e.func.attr)
            return f"{obj}.{meth}({', '.join(args)})"
        return f"/* [any2enforce:error] unsupported callee */ 0"

    def _str_call(self, e: CallExpr, args: List[str]) -> str:
        """str(x) -> x (string) / x.ToString() (int/float) / string.ToString(x)."""
        if not args:
            return '""'
        t = self._expr_type(e.args[0])
        if t is STRING:
            return args[0]
        if t is INT or t is FLOAT:
            return f"{args[0]}.ToString()"
        return f"string.ToString({args[0]})"

    def _abs_call(self, e: CallExpr, args: List[str]) -> str:
        if not args:
            return "0"
        t = self._expr_type(e.args[0])
        if t is INT:
            return f"Math.AbsInt({args[0]})"  # verified: Math.AbsInt, not Math.Abs
        if t is FLOAT:
            return f"Math.AbsFloat({args[0]})"  # verified: Math.AbsFloat
        self.diag.error(
            "abs-type",
            "abs() needs an int or float argument in v0.1",
            e.span,
        )
        return f"Math.AbsFloat({args[0]})"

    def _minmax_call(self, e: CallExpr, name: str, args: List[str]) -> str:
        if len(args) != 2:
            self.diag.error(
                f"builtin-{name}",
                f"{name}() with != 2 arguments is not supported in v0.1",
                e.span,
            )
            return "0"
        t0 = self._expr_type(e.args[0])
        t1 = self._expr_type(e.args[1])
        if t0 is INT and t1 is INT:
            fn = "Math.MinInt" if name == "min" else "Math.MaxInt"
        else:
            fn = "Math.Min" if name == "min" else "Math.Max"
        return f"{fn}({args[0]}, {args[1]})"

    def _print_call(self, e: CallExpr, args: List[str]) -> str:
        """print(...) -> Print(x) / PrintFormat("%1 %2 ...", a, b)
        (verified: `proto void Print(void var, ...)`, `proto void
        PrintFormat(string fmt, void param1..param9 = NULL, ...)`)"""
        if not args:
            return 'Print("")'
        if len(args) == 1:
            return f"Print({args[0]})"
        if len(args) <= 9:
            parts = " ".join(f"%{i+1}" for i in range(len(args)))
            return f'PrintFormat("{parts}", {", ".join(args)})'
        self.diag.error(
            "print-arity",
            "print() with more than 9 arguments is not supported in v0.1",
            e.span,
        )
        parts = " ".join(f"%{i+1}" for i in range(9))
        return f'PrintFormat("{parts}", {", ".join(args[:9])})'

    def _len_call(self, e: CallExpr, args: List[str]) -> str:
        if not args:
            return "0"
        arg = e.args[0]
        arg_type = self._expr_type(arg)
        if isinstance(arg_type, ArrayType) or isinstance(arg_type, (MapType, SetType)):
            return f"{args[0]}.Count()"
        if arg_type is STRING:
            return f"{args[0]}.Length()"
        self.diag.error(
            "len-type",
            "len() on an unknown type; mapped to .Count() (verify)",
            e.span,
        )
        return f"{args[0]}.Count()"

    def _fstring(self, e: JoinedStrExpr) -> str:
        """f-string -> string.Format("...%1...", args) (verified API:
        `static proto string Format(string fmt, void param1..param9 = NULL)`)"""
        fmt = ""
        args: List[str] = []
        n = 0
        for is_expr, part in e.parts:
            if is_expr:
                n += 1
                fmt += f"%{n}"
                args.append(self._expr(part))
            else:
                fmt += part
        if n == 0:
            return f'"{_escape(fmt)}"'
        return f'string.Format("{_escape(fmt)}", {", ".join(args)})'

    # ==================================================================
    # identifiers / atoms
    # ==================================================================
    def _attr_access(self, e: AttributeExpr) -> str:
        if _is_super_expr(e.value):
            return f"super.{e.attr}"  # super().attr (verified convention)
        obj = self._expr(e.value)
        if obj == "this":
            # self.field -> bare m_x, self.method -> bare method (verified
            # convention: engine code accesses fields without `this.`)
            if e.attr in self._field_names:
                return self._field_id(e.attr)
            if e.attr in self._method_names:
                return self._method_id(e.attr)
        return f"{obj}.{e.attr}"

    def _const(self, e: ConstExpr) -> str:
        v = e.value
        if v is None:
            return "null"
        if v is True:
            return "true"
        if v is False:
            return "false"
        if isinstance(v, str):
            return f'"{_escape(v)}"'
        if isinstance(v, float):
            return repr(v)
        return str(v)

    def _p(self, e: Expr) -> str:
        if isinstance(e, (NameExpr, ConstExpr, AttributeExpr, CallExpr,
                          SubscriptExpr, ListExpr, JoinedStrExpr)):
            return self._expr(e)
        return f"({self._expr(e)})"

    def _expr_type(self, e: Expr) -> Optional[Type]:
        """Best-effort type lookup for expression nodes (set by sema)."""
        if isinstance(e, NameExpr):
            return self._locals.get(e.name)
        t = getattr(e, "type", None)
        if isinstance(t, Type):
            return t
        return None

    def _dict_types(self, d: DictExpr):
        kt = vt = None
        if d.items:
            k = getattr(d.items[0][0], "type", None)
            v = getattr(d.items[0][1], "type", None)
            kt = k if isinstance(k, Type) and not isinstance(k, ErrorType) else None
            vt = v if isinstance(v, Type) and not isinstance(v, ErrorType) else None
        return kt, vt

    def _field_default(self, t: Type) -> str:
        if isinstance(t, ScalarType):
            return {"int": "0", "float": "0.0", "bool": "false", "string": '""'}.get(t.name, "0")
        return "null"

    # ------------------------------------------------------------------
    # naming policy
    # ------------------------------------------------------------------
    def _type(self, t: Type) -> str:
        return t.render()

    def _field_type(self, t: Type) -> str:
        """Class fields of array/map/set type must be `ref` (verified ANNA:
        `protected static ref array<float> s_Means;`). ClassType.render
        already includes `ref Foo`."""
        if isinstance(t, (ArrayType, MapType, SetType)):
            return "ref " + t.render()
        return t.render()

    def _type_id(self, name: str) -> str:
        return self._check(name)

    def _fn_id(self, name: str) -> str:
        out = _to_pascal(name) if self.policy == "camel" else name
        return self._check(out)

    def _global_fn_id(self, name: str) -> str:
        """Global (module-level) function name: prefix + policy-adjusted name.
        EnforceScript compiles all scripts into one flat namespace, so module
        functions need a project-wide unique prefix (ANNA uses ANNA_)."""
        return self._check(self.prefix + self._fn_id(name))

    def _method_id(self, name: str) -> str:
        return self._fn_id(name)

    def _var_id(self, name: str) -> str:
        if name == "this":  # deliberate keyword usage, never renamed
            return "this"
        out = _to_camel(name) if self.policy == "camel" else name
        return self._check(out)

    def _field_id(self, name: str) -> str:
        return self._check(self.field_prefix + _to_camel(name) if self.policy == "camel"
                           else self.field_prefix + name)

    def _check(self, ident: str) -> str:
        if ident in RESERVED:
            self.diag.warning(
                "reserved-word",
                f"identifier '{ident}' is reserved in EnforceScript; "
                f"renamed to '_{ident}'",
            )
            return "_" + ident
        return ident

    # ------------------------------------------------------------------
    def _line(self, text: str = "") -> None:
        if text:
            self.lines.append("    " * self.indent + text)
        else:
            self.lines.append("")

    def _emit_doc_comment(self, doc: str) -> None:
        for line in doc.strip().splitlines():
            self._line(f"// {line}")

    def _emit_todos(self, todos: List[str]) -> None:
        for t in todos:
            self._line(f"// TODO[{t}]")


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------

def _is_simple(e: Expr) -> bool:
    return isinstance(e, (NameExpr, ConstExpr))


def _is_super_expr(e: Expr) -> bool:
    """True for `super()` (the call node, before an attribute access)."""
    return (isinstance(e, CallExpr)
            and isinstance(e.func, NameExpr)
            and e.func.name == "super"
            and not e.args
            and not e.kwargs)


def _escape(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")
    return out


def _to_camel(name: str) -> str:
    head, _, tail = name.partition("_")
    return head + tail.title().replace("_", "")


def _to_pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def _convert_py_format(s: str):
    """Map Python old-style % placeholders (%s %d %f %r) to EnforceScript
    format() positional placeholders (%1, %2, ...). Returns (new_string, count)."""
    out: List[str] = []
    i = 0
    n = 0
    while i < len(s):
        ch = s[i]
        if ch == "%":
            if i + 1 < len(s) and s[i + 1] == "%":
                out.append("%")
                i += 2
                continue
            j = i + 1
            while j < len(s) and s[j] in "0123456789.-+ #hlL":
                j += 1
            if j < len(s) and s[j] in "sdifr":
                n += 1
                out.append(f"%{n}")
                i = j + 1
                continue
            out.append("%")
            i += 1
            continue
        out.append(ch)
        i += 1
    return "".join(out), n

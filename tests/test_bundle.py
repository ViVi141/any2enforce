def test_bundle_unresolved_import():
    """Unresolvable import produces a diagnostic (no crash)."""
    entry = str(FIXTURES / "unresolved_main.py")
    modules, text, diag = transpile_bundle(entry)
    # Should have at least one unresolved import error
    assert any(d.code == "bundle-unresolved-import" for d in diag.errors), \
        [d.code for d in diag.errors]
    # Entry module itself is still returned
    assert modules



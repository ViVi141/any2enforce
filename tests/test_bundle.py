def test_qn_to_ns_prefix():
    assert qn_to_ns_prefix("a") == "a_"
    assert qn_to_ns_prefix("a.b.c") == "a_b_c_"
    assert qn_to_ns_prefix("pkg.module") == "pkg_module_"


def test_resolver_sibling_import():
    from any2enforce.diagnostics import DiagnosticSink
    r = Resolver(DiagnosticSink())
    modules = r.resolve_closure(str(FIXTURES / "main_import.py"))
    assert len(modules) == 2
    names = {m.name for m in modules}
    assert names == {"main_import", "util"}